"""Renders runs/scrum94/results.json as markdown tables. Generated, never typed."""
import json
import sys
from pathlib import Path

NAMES = {
    "selected": "SELECTED - fixed target, BF >= 4 and P > 0.5",
    "posterior_only": "belief only - P >= 0.8",
    "bf_only": "evidence only - BF >= 4",
    "fixed_target_no_prior": "fixed target, no prior - P_flat >= 0.8",
    "pre_post": "pre/post - P(above baseline) >= 0.8",
    "naive": "naive - 3 of last 4 (SCRUM-93)",
    "bkt_oracle_ALL": "BKT 0.95, population params (known population), all answers",
    "bkt_oracle_INDEP": "BKT 0.95, population params (known population), independent answers",
    "bkt_fitted_ALL": "BKT 0.95, fitted params, all answers",
    "bkt_fitted_INDEP": "BKT 0.95, fitted params, independent answers",
    "bkt_seeded": "BKT 0.95 seeded with the baseline",
    "bkt_fitted_ALL_3way": "BKT, fitted, all answers, 3-way (>= 0.95 / <= 0.05)",
    "bkt_fitted_INDEP_3way": "BKT, fitted, independent answers, 3-way (>= 0.95 / <= 0.05)",
}


def pct(w):
    if not w:
        return "n/a"
    return f"{w['p']:.1%} [{w['lo']:.1%}, {w['hi']:.1%}] ({w['k']}/{w['n']})"


def ci(c):
    return "n/a" if not c else f"[{c[0]:.1%}, {c[1]:.1%}]"


def main_table(block, target, title):
    lines = [f"### {title}", "",
             "| method | false DEMONSTRATED | cluster CI | miss | cluster CI | wrong NOT_YET | INSUFFICIENT | wrong decisions (all cases) | error among decided |",
             "|---|---|---|---|---|---|---|---|---|"]
    for m, rows in block[target].items():
        r = rows["ALL"]
        lines.append(f"| {NAMES[m]} | {pct(r['false_demonstrated'])} | "
                     f"{ci(r.get('false_demonstrated_cluster'))} | {pct(r['miss'])} | "
                     f"{ci(r.get('miss_cluster'))} | {pct(r['wrong_not_yet'])} | "
                     f"{pct(r['insufficient'])} | {pct(r['wrong_decisions'])} | "
                     f"{pct(r['error_among_decided'])} |")
    return lines + [""]


def pop_table(block, method, target="known"):
    lines = [f"#### {NAMES[method]} - by population (truth: {target})", "",
             "| population | n | truly at target | false DEMONSTRATED | miss | INSUFFICIENT |",
             "|---|---|---|---|---|---|"]
    for p, r in block[target][method].items():
        if p == "ALL":
            continue
        lines.append(f"| {p} | {r['n']} | {r['positives']} | {pct(r['false_demonstrated'])} | "
                     f"{pct(r['miss'])} | {pct(r['insufficient'])} |")
    return lines + [""]


def render(R) -> str:
    out = ["# SCRUM-94 - intervention verdict: validation results", "",
           "**SIMULATION RESULT.** Generated by `harness/validate94.py`; every rate has its "
           "sample (k/n), a 95% Wilson interval, and for the pooled rows a 95% cluster "
           "bootstrap interval over learners (a learner's three concepts are not independent: "
           "report the cluster interval when the two differ).", "",
           "Unit: one (learner, concept), judged at the end of its immediate post-test. "
           "Truth `known`: knows the concept when the post-test begins. Truth `learned`: "
           "knows and the twin without the intervention does not.", "",
           "Binary methods (naive, BKT 0.95) never abstain: every case they do not call "
           "DEMONSTRATED counts as NOT_YET, so for them `wrong NOT_YET` equals `miss`. "
           "`wrong decisions` counts DEMONSTRATED-but-does-not-know plus NOT_YET-but-knows over "
           "ALL cases, so abstaining methods and deciding methods are compared on one scale.", "",
           f"Fitted BKT (Baum-Welch on the calibration run): "
           + "; ".join(f"{m}: " + ", ".join(f"{k} {v:.3f}" for k, v in f.items() if k != "loglik")
                       for m, f in R["fitted_bkt"].items()), ""]
    for key, L in (("main_L3", 3), ("main_L8", 8)):
        out += [f"## Main comparison, post-test of {L} items per concept", ""]
        out += main_table(R[key], "known", f"truth = knows now (the verdict's question), L = {L}")
        out += main_table(R[key], "learned", f"truth = learned because of the intervention (causal - not the verdict's claim), L = {L}")
        for m in ("selected", "naive", "bkt_fitted_ALL", "bkt_fitted_INDEP"):
            out += pop_table(R[key], m)
    out += ["## Evidence needed (post-test length L)", "",
            "| L | baseline | median n0 | decided | false DEMONSTRATED | miss | ever DEMONSTRATED while not knowing (sequential) | answers to first DEMONSTRATED (knows): median / p90 | answers to first NOT_YET (does not know): median / p90 |",
            "|---|---|---|---|---|---|---|---|---|"]
    for L, row in sorted(R["evidence_needed"].items(), key=lambda kv: int(kv[0])):
        for b in ("standin", "strong"):
            x = row[b]
            d1, d2 = x["first_k_to_DEMONSTRATED_knows"], x["first_k_to_NOT_YET_not_knows"]
            f = lambda d: "-" if not d else f"{d['median']} / {d['p90']} (n {d['n']})"
            out.append(f"| {L} | {'weak (stand-in)' if b == 'standin' else 'strong (n = 30, same mean)'} | "
                       f"{x['baseline_n_median']:.1f} | {pct(x['decided'])} | "
                       f"{pct(x['rates']['false_demonstrated'])} | {pct(x['rates']['miss'])} | "
                       f"{pct(x['ever_demonstrated_not_knows'])} | {f(d1)} | {f(d2)} |")
    out += ["", "| L | method | false DEMONSTRATED | miss | wrong NOT_YET | wrong decisions | decided |",
            "|---|---|---|---|---|---|---|"]
    for L, row in sorted(R["evidence_needed"].items(), key=lambda kv: int(kv[0])):
        x = row["standin"]["rates"]
        out.append(f"| {L} | {NAMES['selected']} | {pct(x['false_demonstrated'])} | {pct(x['miss'])} | "
                   f"{pct(x['wrong_not_yet'])} | {pct(x['wrong_decisions'])} | {pct(x['decided'])} |")
        for m in ("naive", "bkt_fitted_ALL", "bkt_fitted_INDEP", "bkt_oracle_INDEP",
                  "bkt_fitted_INDEP_3way"):
            x = row[m]
            out.append(f"| {L} | {NAMES[m]} | {pct(x['false_demonstrated'])} | {pct(x['miss'])} | "
                       f"{pct(x['wrong_not_yet'])} | {pct(x['wrong_decisions'])} | {pct(x['decided'])} |")
    out += ["", "## Mis-estimated baselines", ""]
    for L, block in sorted(R["misestimated"].items(), key=lambda kv: int(kv[0])):
        for pname, r in block.items():
            b = r["baseline"]
            out += [f"### {pname} - baseline Beta({b['alpha']}, {b['beta']}), mu0 {b['mu0']:.2f}, "
                    f"n {b['n']:.0f}; post-test L = {L}", "",
                    "| method | DEMONSTRATED, learned nothing | DEMONSTRATED, below target | miss, knows |",
                    "|---|---|---|---|"]
            for m in ("selected", "pre_post", "posterior_only", "bf_only", "bkt_seeded"):
                x = r[m]
                out.append(f"| {NAMES[m]} | {pct(x['false_dem_learned_nothing'])} | "
                           f"{pct(x['false_dem_below_target'])} | {pct(x['miss_knows'])} |")
            out.append("")
    out += ["## Exclusions", "", "Reasons on the clean stream, L = 3 (every answer of the "
            "concept, as the verdict judged it):", "",
            "| reason | answers |", "|---|---|"]
    for k, v in R["exclusions_L3"].items():
        out.append(f"| {k} | {v} |")
    for key in ("contamination_L3", "contamination_L8"):
        out += ["", f"### Injected answers ({key})", ""]
        for variant, x in R[key].items():
            out += [f"**{variant}**: verdict identical (outcome, P, BF) in "
                    f"{x['verdict_identical']} of {x['cases']} cases; injected answers with an "
                    f"unexpected reason: {x['injected_with_unexpected_reason']}.", "",
                    "| injected -> recorded reason | answers |", "|---|---|"]
            for k, v in x["injected_reasons"].items():
                out.append(f"| {k} | {v} |")
            out += ["", "Naive rule, clean -> contaminated: " + ", ".join(
                f"{k}: {v}" for k, v in x["naive_rule_clean_to_contaminated"].items()), ""]
    out += ["## Baseline (stand-in) by population, L = 3", "",
            "| population | cases | mu0 median | min | max |", "|---|---|---|---|---|"]
    for p, x in R["baseline_summary_L3"].items():
        out.append(f"| {p} | {x['n']} | {x['mu0_median']:.3f} | {x['mu0_min']:.3f} | {x['mu0_max']:.3f} |")
    m = R["manifest"]
    out += ["", "## Manifest", "", f"- code sha256 `{m['code_sha256']}`",
            f"- verdicts sha256 `{m['verdicts_sha256']}`", f"- calibration `{m['calibration']}`"]
    out += [f"- {k}: `{v}`" for k, v in sorted(m["inputs"].items())]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    p = Path(sys.argv[1] if len(sys.argv) > 1 else "runs/scrum94/results.json")
    print(render(json.loads(p.read_text(encoding="utf-8"))))
